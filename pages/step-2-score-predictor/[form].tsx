import Link from 'next/link';
import { GetStaticPaths, GetStaticProps } from 'next';
import {
  AppShell, ArticleBody, ArticleHeader, Callout, Faq, Hero, Section, StoreButton, Table,
} from '../../components/app';
import { PageHead, ResearchStyles, W820 } from '../../components/app/research';
import { FORM_PAGES, FormPage, formPageBySlug, allFormSlugs } from '../../lib/forms';
import {
  CAL, PASS, formOffset, correctedScore, calibratedCenter, bandHalfWidth, percentile, ordinal,
} from '../../lib/readiness';
import OUTCOMES from '../../lib/form_outcomes.json';

// One page per practice form, the structure students actually search
// ("nbme 15 score conversion"). The table is the reason the page exists: a
// printed score maps to a RANGE, computed with the same constants as
// /readiness and the app, so nothing here can drift from the live model.
//
// Table assumption: taken within the last month, which is the 11 point band.
// Stated on the page rather than buried, because the band is the honest part.
// Built from the app-look blocks (components/app/README.md).
const TABLE_BAND = bandHalfWidth(21);          // "Moderate", +/- 11
const TABLE_SCORES = [200, 205, 210, 215, 220, 225, 230, 235, 240, 245, 250, 255, 260, 265, 270];

type Row = { printed: number; lo: number; hi: number; mid: number; pctl: number; pass: boolean };

function rows(form: string): Row[] {
  return TABLE_SCORES.map((printed) => {
    const center = calibratedCenter(correctedScore(form, printed));
    const lo = center - TABLE_BAND.band;
    const hi = center + TABLE_BAND.band;
    return { printed, lo, hi, mid: center, pctl: percentile(center), pass: lo >= PASS };
  });
}

export default function FormConversion({ page }: { page: FormPage }) {
  const off = formOffset(page.form);
  const table = rows(page.form);
  const campaign = `predictor_${page.slug.replace(/-/g, '')}`;
  const others = FORM_PAGES.filter((f) => f.slug !== page.slug);
  const canonical = `https://stepgunner.com/step-2-score-predictor/${page.slug}`;
  // Observed outcomes for this form, from lib/form_outcomes.json (generated by
  // scripts/gen_form_outcomes.py in the app repo). Optional: a form with too few
  // paired records is omitted there rather than published thin.
  const outcome = (OUTCOMES.forms as Record<string, {
    form: string; n: number; medianPrinted: number; medianActual: number; medianDelta: number;
    bands: { label: string; n: number; median: number; p25: number; p75: number }[];
  }>)[page.slug];
  const toc: [string, string][] = [
    ['table', `${page.form} conversion table`],
    ...(outcome ? [['record', `What ${page.form} actually predicted, for ${outcome.n} students`] as [string, string]] : []),
    ['how', 'How the projection works'],
    ['faq', 'Questions'],
    ['others', 'Other forms'],
  ];

  return (
    <>
      <PageHead metaTitle={page.title} metaDesc={page.description}>
        <link rel="canonical" href={canonical} />
        <meta property="og:title" content={page.h1} />
        <meta property="og:description" content={page.description} />
        <meta property="og:url" content={canonical} />
        <meta property="og:image" content="https://stepgunner.com/api/og" />
        <meta property="og:image:width" content="1200" />
        <meta property="og:image:height" content="630" />
        <meta name="twitter:card" content="summary_large_image" />
        <meta name="twitter:image" content="https://stepgunner.com/api/og" />
        <script
          type="application/ld+json"
          // eslint-disable-next-line react/no-danger
          dangerouslySetInnerHTML={{
            __html: JSON.stringify({
              '@context': 'https://schema.org',
              '@type': 'FAQPage',
              mainEntity: page.faq.map((f) => ({
                '@type': 'Question',
                name: f.q,
                acceptedAnswer: { '@type': 'Answer', text: f.a },
              })),
            }),
          }}
        />
      </PageHead>

      <AppShell campaign={campaign} pageType="tool">
        <ResearchStyles />
        <Hero>
          <ArticleHeader
            category="step2"
            crumb={[{ href: '/step-2-score-predictor', label: 'Step 2 score predictor' }]}
            eyebrow="Score conversion"
            title={page.h1}
            accent="Step 2 CK"
            dek={page.lede}
            byline={false}
          />
          <W820>
            <Callout>
              <p>
                <b>
                  {off === 0
                    ? `${page.form} carries no correction.`
                    : off > 0
                      ? `${page.form} prints about ${Math.abs(off)} points low.`
                      : `${page.form} prints about ${Math.abs(off)} points hot.`}
                </b>{' '}
                {page.note}
              </p>
            </Callout>
          </W820>
        </Hero>

        <ArticleBody toc={toc}>
          <Section id="table" n="" title={`${page.form} conversion table`}>
            <p className="prs">
              Printed score to projected Step 2 CK range, for a form taken in the last month.
              The range is about a 68% band: roughly two in three students land inside it, which
              is why it is a range and not a single number. Take the exam further out and the
              band widens.
            </p>
            <div className="mk isl rs-risk">
              <Table
                label={`${page.form} printed score to projected Step 2 CK range`}
                head={[`${page.form} printed`, 'Projected Step 2 CK', 'Midpoint', 'Percentile']}
                num={[1, 2, 3]}
                hl={table.map((r, i) => (r.pass ? -1 : i)).filter((i) => i >= 0)}
                minWidth={460}
                rows={table.map((r) => [<b key="b">{r.printed}</b>, `${r.lo} to ${r.hi}`, String(r.mid), ordinal(r.pctl)])}
              />
            </div>
            <p className="rs-fine">
              Rows shaded amber have a projected floor below the {PASS} pass line. Percentile is
              against LCME first-takers. Your printed score is never restated as a lower number:
              where a correction applies it lives inside the math, not on your report.
            </p>
            <div className="mk isl">
              <div className="rs-act">
                <Link href="/step-2-score-predictor" className="btn btn-q">
                  Blend several forms and add your exam date
                </Link>
              </div>
            </div>
          </Section>

          {outcome && (
            <Section id="record" n="" title={`What ${page.form} actually predicted, for ${outcome.n} students`}>
              <p className="prs">
                The table above is the model. This one is the record. These are {outcome.n} students
                who posted a {page.form} score and, later, the real Step 2 CK score that followed.
                Median {page.form} was <b>{outcome.medianPrinted}</b>; their median real score was{' '}
                <b>{outcome.medianActual}</b>, a jump of{' '}
                <b>{outcome.medianDelta > 0 ? '+' : ''}{outcome.medianDelta}</b> points.
              </p>
              <Table
                label={`What ${page.form} predicted, by printed band`}
                head={[`${page.form} printed`, 'Students', 'Median real Step 2', 'Middle half landed']}
                num={[1, 2, 3]}
                minWidth={460}
                rows={outcome.bands.map((b) => [<b key="b">{b.label}</b>, String(b.n), String(b.median), `${b.p25} to ${b.p75}`])}
              />
              <p className="rs-fine">
                Self-reported scores posted to public forums, paired per student. People who do well
                post more often than people who do not, so treat these as an optimistic ceiling rather
                than a population average. The middle-half column is the interquartile range: a quarter
                of students in that band finished below it and a quarter above.
              </p>
            </Section>
          )}

          <Section id="how" n="" title="How the projection works">
            <p className="prs">
              Three steps, and the constants are published rather than described.
              {off !== 0 && (
                <> First the printed score is put on the common scale: {page.form}{' '}
                  {off > 0 ? 'gains' : 'loses'} {Math.abs(off)} points inside the math.
                </>
              )}{' '}
              Then it is shrunk toward the population mean of {CAL.mean} with a slope of {CAL.slope},
              which is what stops a single high form from projecting a fantasy. Then {CAL.delta} points
              are added for the measured gain from practice form to real exam.
            </p>
            <p className="prs">
              Fit on 258 real posted score reports and tested blind on 32 it had never seen: average
              miss 4.1 points, bias statistically zero. Reddit posters skew toward good news, so treat
              the range as honest rather than generous.{' '}
              <Link href="/readiness/methodology">Full methodology</Link>, including where the model
              stops being trustworthy.
            </p>
          </Section>

          <Section id="faq" n="" title="Questions">
            <Faq items={page.faq} />
          </Section>

          <Section id="others" n="" title="Other forms">
            <div className="mk isl">
              <div className="gjump">
                {others.map((f) => (
                  <Link key={f.slug} href={`/step-2-score-predictor/${f.slug}`}>{f.form}</Link>
                ))}
              </div>
              <div className="rs-act"><StoreButton loc="end">Get Step Gunner</StoreButton></div>
            </div>
          </Section>
        </ArticleBody>
      </AppShell>
    </>
  );
}

export const getStaticPaths: GetStaticPaths = async () => ({
  paths: allFormSlugs().map((form) => ({ params: { form } })),
  fallback: false,
});

export const getStaticProps: GetStaticProps = async ({ params }) => {
  const page = formPageBySlug(String(params?.form));
  if (!page) return { notFound: true };
  return { props: { page } };
};
